//! Container entrypoint: start the admission hook, then the gateway.
//!
//! The upstream gateway image is distroless (no shell), so this binary is the
//! init process:
//!
//! 1. bind the hook's gRPC listener (default `127.0.0.1:12777`) and serve it;
//! 2. make sure the gateway config registers the hook as an interceptor
//!    (the user's TOML is copied, never modified in place);
//! 3. spawn the gateway with the remaining arguments;
//! 4. forward termination signals, reap orphaned children (we are PID 1) and
//!    exit with the gateway's status.

use std::ffi::OsString;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use tokio::signal::unix::{SignalKind, signal};
use toml_edit::{ArrayOfTables, DocumentMut, Item, Table, value};
use tracing::{error, info, warn};

use crate::hook::{CREATE_SANDBOX_RPC, INTERCEPTOR_NAME};

pub const CONFIG_ENV: &str = "OPENSHELL_GATEWAY_CONFIG";

pub struct LaunchOptions {
    /// Address the hook listens on.
    pub listen: std::net::SocketAddr,
    /// Endpoint written into the gateway config.
    pub endpoint: String,
    /// Whether to inject the interceptor registration into the gateway config.
    pub inject_config: bool,
    /// Where the generated gateway config is written.
    pub runtime_dir: PathBuf,
    /// Interceptor RPC timeout written into the config.
    pub timeout: String,
    /// Gateway program followed by its arguments.
    pub command: Vec<OsString>,
}

// ---- config injection --------------------------------------------------------

/// Finds `--config <path>` / `--config=<path>` in gateway args.
/// Returns (index of the value, path).
fn find_config_arg(args: &[OsString]) -> Option<(usize, PathBuf)> {
    let mut i = 0;
    while i < args.len() {
        let a = args[i].to_string_lossy();
        if a == "--" {
            return None;
        }
        if a == "--config" {
            return args.get(i + 1).map(|v| (i + 1, PathBuf::from(v)));
        }
        if let Some(v) = a.strip_prefix("--config=") {
            return Some((i, PathBuf::from(v)));
        }
        i += 1;
    }
    None
}

/// Same discovery the gateway uses when neither `--config` nor the env var is
/// set: `$XDG_CONFIG_HOME/openshell/gateway.toml` or
/// `$HOME/.config/openshell/gateway.toml`.
fn default_config_path() -> Option<PathBuf> {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))?;
    Some(base.join("openshell").join("gateway.toml"))
}

/// Adds (or refreshes) our `[[openshell.gateway.interceptors]]` entry.
pub fn inject_interceptor(source: &str, endpoint: &str, timeout: &str) -> Result<String> {
    let mut doc: DocumentMut = if source.trim().is_empty() {
        DocumentMut::new()
    } else {
        source.parse().context("gateway config is not valid TOML")?
    };

    let openshell = doc
        .entry("openshell")
        .or_insert_with(|| Item::Table(Table::new()))
        .as_table_mut()
        .context("`openshell` in gateway config is not a table")?;
    if !openshell.contains_key("version") {
        openshell.insert("version", value(2));
    }
    let gateway = openshell
        .entry("gateway")
        .or_insert_with(|| Item::Table(Table::new()))
        .as_table_mut()
        .context("`openshell.gateway` in gateway config is not a table")?;
    let interceptors = gateway
        .entry("interceptors")
        .or_insert_with(|| Item::ArrayOfTables(ArrayOfTables::new()))
        .as_array_of_tables_mut()
        .context("`openshell.gateway.interceptors` must be an array of tables")?;

    // Drop a previous registration of ours (e.g. a config generated by an
    // older image), then append a fresh one.
    interceptors.retain(|t| t.get("name").and_then(Item::as_str) != Some(INTERCEPTOR_NAME));

    let mut binding = Table::new();
    binding.insert("rpc", value(CREATE_SANDBOX_RPC));
    let mut phases = toml_edit::Array::new();
    phases.push("modify_operation");
    binding.insert("phases", value(phases));
    let mut bindings = ArrayOfTables::new();
    bindings.push(binding);

    let mut t = Table::new();
    t.insert("name", value(INTERCEPTOR_NAME));
    t.insert("grpc_endpoint", value(endpoint));
    if endpoint.starts_with("http://") {
        // Loopback plaintext inside the container; no bearer token attached.
        t.insert("allow_insecure_transport", value(true));
    }
    // Run before any other interceptor so later validators see Linux paths.
    t.insert("order", value(-1000));
    t.insert("failure_policy", value("fail_closed"));
    t.insert("binding_policy", value("exact"));
    t.insert("timeout", value(timeout));
    t.insert("bindings", Item::ArrayOfTables(bindings));
    interceptors.push(t);

    Ok(doc.to_string())
}

fn write_private_file(dir: &Path, name: &str, contents: &str) -> Result<PathBuf> {
    use std::io::Write as _;
    use std::os::unix::fs::{DirBuilderExt as _, OpenOptionsExt as _, PermissionsExt as _};

    std::fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(dir)
        .with_context(|| format!("creating {}", dir.display()))?;
    std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700)).ok();
    let path = dir.join(name);
    match std::fs::remove_file(&path) {
        Ok(()) => {}
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(e).with_context(|| format!("removing stale {}", path.display())),
    }
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(&path)
        .with_context(|| format!("creating {}", path.display()))?;
    f.write_all(contents.as_bytes())?;
    f.sync_all()?;
    Ok(path)
}

/// Returns the gateway argv and an optional `OPENSHELL_GATEWAY_CONFIG` value.
fn prepare_gateway_config(opts: &LaunchOptions) -> Result<(Vec<OsString>, Option<PathBuf>)> {
    let mut argv = opts.command.clone();
    if !opts.inject_config {
        return Ok((argv, None));
    }
    let args = &argv[1..];
    let from_arg = find_config_arg(args);
    let source_path = match &from_arg {
        Some((_, p)) => Some(p.clone()),
        None => match std::env::var_os(CONFIG_ENV).filter(|v| !v.is_empty()) {
            Some(p) => Some(PathBuf::from(p)),
            None => default_config_path().filter(|p| p.exists()),
        },
    };

    let original = match &source_path {
        Some(p) => {
            info!(config = %p.display(), "registering admission hook in gateway config");
            std::fs::read_to_string(p)
                .with_context(|| format!("reading gateway config {}", p.display()))?
        }
        None => {
            info!("no gateway config found; generating one that registers the admission hook");
            String::new()
        }
    };
    let merged = inject_interceptor(&original, &opts.endpoint, &opts.timeout)?;
    let generated = write_private_file(&opts.runtime_dir, "gateway.toml", &merged)?;
    info!(config = %generated.display(), "gateway will use generated config");

    match from_arg {
        Some((idx, _)) => {
            let idx = idx + 1; // offset of argv[0]
            let current = argv[idx].to_string_lossy().into_owned();
            argv[idx] = if current.starts_with("--config=") {
                OsString::from(format!("--config={}", generated.display()))
            } else {
                generated.clone().into_os_string()
            };
            Ok((argv, None))
        }
        None => Ok((argv, Some(generated))),
    }
}

// ---- process supervision -----------------------------------------------------

fn exit_code(status: libc::c_int) -> i32 {
    if libc::WIFEXITED(status) {
        libc::WEXITSTATUS(status)
    } else if libc::WIFSIGNALED(status) {
        128 + libc::WTERMSIG(status)
    } else {
        1
    }
}

/// Reaps every exited child. Returns the gateway's exit code if it is among them.
fn reap(gateway_pid: libc::pid_t) -> Option<i32> {
    let mut gateway_code = None;
    loop {
        let mut status: libc::c_int = 0;
        // SAFETY: plain waitpid(2) on any child, non-blocking.
        let pid = unsafe { libc::waitpid(-1, &mut status, libc::WNOHANG) };
        if pid <= 0 {
            break;
        }
        if pid == gateway_pid {
            gateway_code = Some(exit_code(status));
        }
    }
    gateway_code
}

fn forward(pid: libc::pid_t, sig: libc::c_int) {
    // SAFETY: kill(2) on our own child.
    unsafe {
        libc::kill(pid, sig);
    }
}

pub async fn run(opts: LaunchOptions, hook: crate::hook::AdmissionHook) -> Result<i32> {
    if opts.command.is_empty() {
        bail!(
            "no gateway command given (usage: launch -- /usr/local/bin/openshell-gateway [ARGS...])"
        );
    }

    // Install handlers before spawning anything so no signal is lost.
    let mut sigchld = signal(SignalKind::child())?;
    let mut sigterm = signal(SignalKind::terminate())?;
    let mut sigint = signal(SignalKind::interrupt())?;
    let mut sigquit = signal(SignalKind::quit())?;
    let mut sighup = signal(SignalKind::hangup())?;

    // 1. Admission hook first: the listener is bound before the gateway
    //    exists, so the gateway's startup Describe call can't race it.
    let listener = tokio::net::TcpListener::bind(opts.listen)
        .await
        .with_context(|| format!("binding admission hook on {}", opts.listen))?;
    info!(listen = %opts.listen, "admission hook listening");
    let mut server = tokio::spawn(crate::serve_listener(listener, hook));

    // 2. Gateway config.
    let (argv, config_env) = prepare_gateway_config(&opts)?;

    // 3. Gateway.
    let mut cmd = Command::new(&argv[0]);
    cmd.args(&argv[1..]);
    if let Some(p) = &config_env {
        cmd.env(CONFIG_ENV, p);
    }
    let child = cmd
        .spawn()
        .with_context(|| format!("starting gateway {:?}", argv[0]))?;
    let pid = child.id() as libc::pid_t;
    // The child is reaped by `reap`, never through std's handle.
    std::mem::forget(child);
    info!(pid, "gateway started");

    // 4. Supervise.
    loop {
        tokio::select! {
            _ = sigchld.recv() => {
                if let Some(code) = reap(pid) {
                    info!(code, "gateway exited");
                    server.abort();
                    return Ok(code);
                }
            }
            _ = sigterm.recv() => { info!("SIGTERM: stopping gateway"); forward(pid, libc::SIGTERM); }
            _ = sigint.recv()  => { info!("SIGINT: stopping gateway");  forward(pid, libc::SIGINT); }
            _ = sigquit.recv() => { forward(pid, libc::SIGQUIT); }
            _ = sighup.recv()  => { forward(pid, libc::SIGHUP); }
            res = &mut server => {
                match res {
                    Ok(Ok(())) => error!("admission hook stopped unexpectedly; stopping gateway"),
                    Ok(Err(e)) => error!(error = %e, "admission hook failed; stopping gateway"),
                    Err(e) => error!(error = %e, "admission hook task panicked; stopping gateway"),
                }
                forward(pid, libc::SIGTERM);
                // Wait for the gateway to go away, escalating after a grace period.
                let deadline = tokio::time::sleep(std::time::Duration::from_secs(30));
                tokio::pin!(deadline);
                loop {
                    tokio::select! {
                        _ = sigchld.recv() => {
                            if reap(pid).is_some() { return Ok(1); }
                        }
                        () = &mut deadline => {
                            warn!("gateway did not stop in time; sending SIGKILL");
                            forward(pid, libc::SIGKILL);
                            deadline.as_mut().reset(tokio::time::Instant::now() + std::time::Duration::from_secs(5));
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn os(v: &[&str]) -> Vec<OsString> {
        v.iter().map(OsString::from).collect()
    }

    #[test]
    fn finds_config_argument_forms() {
        assert_eq!(
            find_config_arg(&os(&["--port", "8080", "--config", "/etc/g.toml"])),
            Some((3, PathBuf::from("/etc/g.toml")))
        );
        assert_eq!(
            find_config_arg(&os(&["--config=/etc/g.toml"])),
            Some((0, PathBuf::from("/etc/g.toml")))
        );
        assert_eq!(find_config_arg(&os(&["--port", "8080"])), None);
        assert_eq!(find_config_arg(&os(&["--", "--config", "x"])), None);
    }

    #[test]
    fn injects_into_empty_config() {
        let out = inject_interceptor("", "http://127.0.0.1:12777", "2s").unwrap();
        let doc: toml_edit::DocumentMut = out.parse().unwrap();
        assert_eq!(doc["openshell"]["version"].as_integer(), Some(2));
        let list = doc["openshell"]["gateway"]["interceptors"]
            .as_array_of_tables()
            .unwrap();
        assert_eq!(list.len(), 1);
        let t = list.get(0).unwrap();
        assert_eq!(t["name"].as_str(), Some(INTERCEPTOR_NAME));
        assert_eq!(t["grpc_endpoint"].as_str(), Some("http://127.0.0.1:12777"));
        assert_eq!(t["allow_insecure_transport"].as_bool(), Some(true));
        assert_eq!(t["failure_policy"].as_str(), Some("fail_closed"));
        assert_eq!(t["binding_policy"].as_str(), Some("exact"));
        let b = t["bindings"].as_array_of_tables().unwrap().get(0).unwrap();
        assert_eq!(b["rpc"].as_str(), Some(CREATE_SANDBOX_RPC));
        assert_eq!(
            b["phases"].as_array().unwrap().get(0).unwrap().as_str(),
            Some("modify_operation")
        );
    }

    #[test]
    fn preserves_existing_config_and_interceptors() {
        let src = r#"# user comment
[openshell]
version = 2

[openshell.gateway]
compute_driver = "podman"
disable_tls = true

[[openshell.gateway.interceptors]]
name = "quota"
grpc_endpoint = "unix:///run/quota.sock"

[[openshell.gateway.interceptors.bindings]]
rpc = "openshell.v1.OpenShell/CreateSandbox"
phases = ["validate"]

[openshell.drivers.podman]
enable_bind_mounts = true
"#;
        let out = inject_interceptor(src, "http://127.0.0.1:12777", "2s").unwrap();
        assert!(out.contains("# user comment"));
        let doc: toml_edit::DocumentMut = out.parse().unwrap();
        assert_eq!(
            doc["openshell"]["gateway"]["compute_driver"].as_str(),
            Some("podman")
        );
        assert_eq!(
            doc["openshell"]["drivers"]["podman"]["enable_bind_mounts"].as_bool(),
            Some(true)
        );
        let list = doc["openshell"]["gateway"]["interceptors"]
            .as_array_of_tables()
            .unwrap();
        let names: Vec<_> = list.iter().map(|t| t["name"].as_str().unwrap()).collect();
        assert_eq!(names, vec!["quota", INTERCEPTOR_NAME]);
        // The quota interceptor kept its binding.
        assert_eq!(
            list.get(0).unwrap()["bindings"]
                .as_array_of_tables()
                .unwrap()
                .len(),
            1
        );
    }

    #[test]
    fn injection_is_idempotent() {
        let once = inject_interceptor("", "http://127.0.0.1:12777", "2s").unwrap();
        let twice = inject_interceptor(&once, "http://127.0.0.1:12777", "2s").unwrap();
        let doc: toml_edit::DocumentMut = twice.parse().unwrap();
        assert_eq!(
            doc["openshell"]["gateway"]["interceptors"]
                .as_array_of_tables()
                .unwrap()
                .len(),
            1
        );
    }

    #[test]
    fn https_endpoint_does_not_allow_insecure_transport() {
        let out = inject_interceptor("", "unix:///run/hook.sock", "2s").unwrap();
        assert!(!out.contains("allow_insecure_transport"));
    }

    #[test]
    fn rejects_invalid_toml() {
        assert!(inject_interceptor("[openshell", "http://x:1", "2s").is_err());
    }
}
